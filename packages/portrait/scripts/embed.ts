/**
 * Turns the embed build (dist-embed/index.html, one file with JS and CSS inlined) into a TypeScript module the Expo
 * app bundles, so the portrait works on a phone with no network path to a laptop. Holds code only, never data.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const html = readFileSync(resolve(root, "dist-embed/index.html"), "utf8");
const out = resolve(root, "../mobile/src/components/portraitHtml.ts");
writeFileSync(
  out,
  "/** Generated by \`pnpm --filter @textrovert/portrait build:embed\` from packages/portrait; don't edit by hand. */\n" +
    "export const PORTRAIT_HTML = " + JSON.stringify(html) + ";\n",
);
console.log("wrote", out, Math.round(html.length / 1024) + " KB");
